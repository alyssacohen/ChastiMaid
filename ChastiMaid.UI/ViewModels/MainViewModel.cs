using ReactiveUI.SourceGenerators;
using ChastiMaid.Core.Services;

namespace ChastiMaid.UI.ViewModels;

/// <summary>
/// Main application view model managing navigation and session lifecycle.
/// Acts as the central coordinator for the application flow.
/// </summary>
public partial class MainViewModel : ViewModelBase
{
    private readonly DatabaseService _dbService;
    private readonly SessionManager _sessionManager;

    [Reactive] private ViewModelBase _currentPage;
    [Reactive] private bool _showConfirmOverlay;

    public MainViewModel()
    {
        _dbService = new DatabaseService("password");
        _sessionManager = new SessionManager(_dbService);

        // Always start at the intro screen
        _currentPage = new IntroViewModel(this, _sessionManager);

        // All commands are autogenerated by SourceGenerators
    }

    /// <summary>
    /// Provides access to the database service for child view models.
    /// </summary>
    public DatabaseService DbService => _dbService;

    /// <summary>
    /// Provides access to the session manager for child view models.
    /// </summary>
    public SessionManager SessionManager => _sessionManager;

    // Commands
    [ReactiveCommand]
    private void StartNewSession()
    {
        // Show confirmation if there's an existing session
        if (_sessionManager.HasExistingSession())
        {
            ShowConfirmOverlay = true;
        }
        else
        {
            // No existing session, go directly to settings
            NavigateToSettings();
        }
    }

    [ReactiveCommand]
    private void ConfirmNewSession()
    {
        ShowConfirmOverlay = false;

        // Delete existing session and start fresh
        _sessionManager.DeleteAllSessions();

        NavigateToSettings();
    }

    [ReactiveCommand]
    private void CancelNewSession()
    {
        ShowConfirmOverlay = false;
    }

    [ReactiveCommand]
    private void ContinueSession()
    {
        // Load existing session
        if (_sessionManager.LoadSession())
        {
            NavigateToDashboard();
        }
        else
        {
            // No session found, prompt to create new one
            StartNewSession();
        }
    }

    [ReactiveCommand]
    private void ExitApp()
    {
        // Save current session before exiting
        if (_sessionManager.CurrentSession != null)
        {
            _sessionManager.SaveSession();
        }

        Environment.Exit(0);
    }

    /// <summary>
    /// Navigates to a different page/view model.
    /// </summary>
    public void NavigateTo(ViewModelBase nextPage)
    {
        // Clean up previous page if it implements IDisposable
        if (CurrentPage is IDisposable disposable)
        {
            disposable.Dispose();
        }

        CurrentPage = nextPage;
    }

    /// <summary>
    /// Navigates to the settings page for creating a new session.
    /// </summary>
    private void NavigateToSettings()
    {
        NavigateTo(new SettingsViewModel(this, _dbService, _sessionManager));
    }

    /// <summary>
    /// Navigates to the main dashboard with the current session loaded.
    /// </summary>
    private void NavigateToDashboard()
    {
        NavigateTo(new DashboardViewModel(this, _dbService, _sessionManager));
    }
}
